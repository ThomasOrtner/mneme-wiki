"""`index.md` generation (BR-6) and `log.md` appends (BR-7).

The index is derived: it is regenerated in full from the pages' front matter and
lead paragraphs, so it can never drift. Its own front matter is kept (only
`updated` changes, and only when the list changed). The log is append-only: an
entry is added at the end, nothing before it is touched.
"""

from __future__ import annotations

import datetime as dt
import re
from collections.abc import Iterable

from . import frontmatter as fm
from . import links, text
from .vault import Page, Vault

INDEX, LOG = "index.md", "log.md"
SECTIONS = (("source", "Sources"), ("entity", "Entities"), ("concept", "Concepts"),
            ("synthesis", "Syntheses"))  # fmt: skip
INDEX_INTRO = (
    "Every page in this wiki, one line each, grouped by type. "
    "Regenerated by `mneme-wiki reindex`; don't edit by hand."
)
LOG_INTRO = (
    "Append-only record of every operation on this wiki, newest last. "
    "Find entries with `grep '^## \\[' log.md`."
)
DESCRIPTION_MAX = 100
_OP = re.compile(r"^[a-z][a-z-]*$")


# ---------------------------------------------------------------------------
# Index
# ---------------------------------------------------------------------------
def index_line(page: Page) -> str:
    """`- [[path|Title]] — first sentence of the lead` for one page."""
    line = "- " + links.format_link(page.path, alias=page.title)
    lead = text.lead(page.body)
    if lead:
        description = text.first_sentence(text.plain(lead.text), DESCRIPTION_MAX)
        if description:
            line += " — " + description
    return line


def render_index_body(pages: Iterable[Page]) -> str:
    by_type: dict[str, list[Page]] = {t: [] for t, _ in SECTIONS}
    for page in pages:
        page_type = page.meta.get("type")
        if page_type in by_type:
            by_type[page_type].append(page)
    out = ["", "# Index", "", INDEX_INTRO, ""]
    for page_type, heading in SECTIONS:
        out += [f"## {heading}", ""]
        entries = sorted(by_type[page_type], key=lambda p: (p.title.casefold(), p.path))
        if entries:
            out += [index_line(p) for p in entries] + [""]
    return "\n".join(out)


def reindex(vault: Vault, *, today: dt.date | None = None) -> bool:
    """Regenerate `index.md`. Pages with unreadable front matter are skipped (lint
    reports them). Returns True if the file changed."""
    day = today or dt.date.today()
    pages = [p for _, p in vault.iter_pages() if isinstance(p, Page) and p.path != INDEX]
    body = render_index_body(pages)
    doc = _existing(vault, INDEX)
    if doc is None:
        doc = fm.new_document({"title": "Index", "type": "index", "created": day}, "")
    if doc.body.replace("\r\n", "\n") == body and doc.raw_front is not None:
        return False
    doc.body = body
    doc.meta["updated"] = day
    return vault.write_text(INDEX, fm.dump(doc))


def _existing(vault: Vault, rel: str) -> fm.Document | None:
    if not vault.exists(rel):
        return None
    try:
        doc = fm.parse(vault.read_text(rel))
    except fm.FrontMatterError:
        return None
    return doc if doc.raw_front is not None else None


# ---------------------------------------------------------------------------
# Log
# ---------------------------------------------------------------------------
def log_entry(op: str, title: str, lines: Iterable[str] = (), *, day: dt.date) -> str:
    """One entry: `## [YYYY-MM-DD] op | title`, a blank line, then `lines`."""
    if not _OP.match(op):
        raise ValueError(f"log op must be a lower-case word, got {op!r}")
    title = " ".join(str(title).split())
    if not title:
        raise ValueError("log entry needs a title")
    entry = f"## [{day.isoformat()}] {op} | {title}\n"
    body = [line.rstrip() for line in lines]
    if body:
        entry += "\n" + "\n".join(body) + "\n"
    return entry


def append_log(
    vault: Vault, op: str, title: str, lines: Iterable[str] = (), *, today: dt.date | None = None
) -> str:
    """Append one entry to `log.md` (created if missing). Returns the entry text."""
    day = today or dt.date.today()
    entry = log_entry(op, title, lines, day=day)
    doc = _existing(vault, LOG)
    if doc is None:
        if vault.exists(LOG):  # unreadable front matter: append without touching it
            current = vault.read_text(LOG)
            vault.write_text(LOG, _join(current, entry, "\r\n" if "\r\n" in current else "\n"))
            return entry
        doc = fm.new_document(
            {"title": "Log", "type": "log", "created": day}, f"\n# Log\n\n{LOG_INTRO}\n"
        )
    doc.body = _join(doc.body, entry, "\n")
    doc.meta["updated"] = day
    vault.write_text(LOG, fm.dump(doc))
    return entry


def _join(current: str, entry: str, newline: str) -> str:
    """`current` + a blank line + `entry` (in the file's newline style)."""
    stripped = current.rstrip("\r\n")
    entry = entry.replace("\n", newline) if newline != "\n" else entry
    return stripped + newline + newline + entry
